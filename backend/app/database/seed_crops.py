async def seed_crop_database(db: AsyncSession) -> int:
    """Idempotently populates and updates the structured crop knowledge database."""
    seeded_count = 0
    for crop_def in CROP_KNOWLEDGE_BASE:
        # Check if crop exists by name
        res = await db.execute(select(Crop).where(Crop.name == crop_def["name"]))
        existing_crop = res.scalar_one_or_none()

        stages_data = crop_def.get("stages", [])
        crop_fields = {k: v for k, v in crop_def.items() if k != "stages"}

        if not existing_crop:
            crop = Crop(**crop_fields)
            db.add(crop)
            await db.flush()  # Get crop.id

            for stage_dict in stages_data:
                stage = CropGrowthStage(crop_id=crop.id, **stage_dict)
                db.add(stage)
            seeded_count += 1
            logger.info(f"Seeded crop catalog for '{crop.name}' with {len(stages_data)} stages.")
        else:
            # Update fields in case schema or agronomic values updated
            for k, v in crop_fields.items():
                setattr(existing_crop, k, v)
            
            # Check if stages exist or need updating
            existing_stages_res = await db.execute(
                select(CropGrowthStage).where(CropGrowthStage.crop_id == existing_crop.id)
            )
            existing_stages = list(existing_stages_res.scalars().all())
            if not existing_stages:
                for stage_dict in stages_data:
                    stage = CropGrowthStage(crop_id=existing_crop.id, **stage_dict)
                    db.add(stage)
                logger.info(f"Added {len(stages_data)} stages to existing crop '{existing_crop.name}'.")

    await db.commit()
    return seeded_count

